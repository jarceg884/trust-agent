_TRUST_LOGIN = r'''#!/usr/bin/env python3
"""trust-login — organization sign-in for the Trust Agent bundle (spec 023).

OIDC authorization-code + PKCE (S256) against your organization's realm:
opens the browser, runs a local callback server (127.0.0.1:8765) and writes
$HERMES_HOME/trust-agent/id-token.txt (0600) — the file the governance
plugin's zero-UI auto-enrollment consumes (spec 022 D-HRB-01).

With --issue-key it ALSO provisions your LiteLLM virtual key (one-time):
mints a control-plane session from the id_token (POST /api/auth/session) and
self-issues the key (POST /api/models/keys), storing it via
`hermes config set model.api_key`. The key material is shown exactly once.

This helper NEVER handles passwords or MFA codes — you type those in the
identity provider's page, never in a terminal.
"""
import base64
import hashlib
import http.server
import json
import os
import secrets
import subprocess
import sys
import threading
import urllib.parse
import urllib.request
import webbrowser

ISSUER = "__ISSUER__"
CLIENT_ID = "__CLIENT_ID__"
API_BASE = "__API_BASE__"
REDIRECT_URI = "http://127.0.0.1:8765/callback"
SCOPE = "openid"
ACR_VALUES = "2"  # MFA (LoA 2) — same requirement as the consoles

HERMES_HOME = os.environ.get("HERMES_HOME") or os.path.join(
    os.path.expanduser("~"), ".hermes"
)


def _b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def fail(msg: str) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def main() -> None:
    issue_key = "--issue-key" in sys.argv
    trust_dir = os.path.join(HERMES_HOME, "trust-agent")
    os.makedirs(trust_dir, exist_ok=True)
    try:
        os.chmod(trust_dir, 0o700)
    except OSError:
        pass

    verifier = _b64url(secrets.token_bytes(48))
    challenge = _b64url(hashlib.sha256(verifier.encode()).digest())
    state = secrets.token_urlsafe(24)
    nonce = secrets.token_urlsafe(16)

    result: dict = {}
    done = threading.Event()

    class CB(http.server.BaseHTTPRequestHandler):
        def log_message(self, *a):  # silence the default stderr noise
            pass

        def do_GET(self):
            parsed = urllib.parse.urlparse(self.path)
            qs = urllib.parse.parse_qs(parsed.query)
            if parsed.path != "/callback":
                self.send_error(404)
                return
            result.update(
                code=(qs.get("code") or [None])[0],
                state=(qs.get("state") or [None])[0],
                error=(qs.get("error") or [None])[0],
            )
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.end_headers()
            self.wfile.write(
                b"<html><body><h3>Sign-in complete.</h3>"
                b"<p>You can close this tab and return to the terminal.</p>"
                b"<script>window.close()</script></body></html>"
            )
            done.set()

    server = http.server.ThreadingHTTPServer(("127.0.0.1", 8765), CB)
    threading.Thread(target=server.serve_forever, daemon=True).start()

    auth_url = (
        f"{ISSUER}/protocol/openid-connect/auth?"
        + urllib.parse.urlencode(
            {
                "response_type": "code",
                "client_id": CLIENT_ID,
                "redirect_uri": REDIRECT_URI,
                "scope": SCOPE,
                "state": state,
                "nonce": nonce,
                "code_challenge": challenge,
                "code_challenge_method": "S256",
                "acr_values": ACR_VALUES,
            }
        )
    )
    print("Opening your organization's sign-in page in the browser...")
    print(f"If it does not open, visit:\n  {auth_url}\n")
    try:
        webbrowser.open(auth_url)
    except Exception:
        pass
    if not done.wait(timeout=600):
        server.shutdown()
        fail("Sign-in timed out (10 minutes). Re-run trust-login.")
    server.shutdown()

    if result.get("error") or not result.get("code"):
        fail(f"Identity provider returned an error: {result.get('error')}")
    if result.get("state") != state:
        fail("State mismatch — possible CSRF. Re-run trust-login.")

    token_url = f"{ISSUER}/protocol/openid-connect/token"
    body = urllib.parse.urlencode(
        {
            "grant_type": "authorization_code",
            "client_id": CLIENT_ID,
            "code": result["code"],
            "redirect_uri": REDIRECT_URI,
            "code_verifier": verifier,
        }
    ).encode()
    req = urllib.request.Request(
        token_url, data=body, method="POST",
        headers={"Content-Type": "application/x-www-form-urlencoded"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        tokens = json.loads(resp.read())

    id_token = tokens.get("id_token")
    if not id_token:
        fail("The identity provider did not return an id_token.")

    token_file = os.path.join(trust_dir, "id-token.txt")
    with open(token_file, "w") as fh:
        fh.write(id_token)
    os.chmod(token_file, 0o600)
    print(f"Signed in. id_token saved to {token_file} (0600).")

    if issue_key:
        sess = json.loads(
            urllib.request.urlopen(
                urllib.request.Request(
                    f"{API_BASE}/api/auth/session",
                    data=json.dumps({"id_token": id_token, "kind": "desktop"}).encode(),
                    method="POST",
                    headers={"Content-Type": "application/json"},
                ),
                timeout=30,
            ).read()
        )
        session_token = sess.get("session_token") or (sess.get("session") or {}).get("session_token")
        if not session_token:
            fail("Session mint succeeded but no session_token in the response.")
        key_resp = json.loads(
            urllib.request.urlopen(
                urllib.request.Request(
                    f"{API_BASE}/api/models/keys",
                    data=b"{}",
                    method="POST",
                    headers={
                        "Content-Type": "application/json",
                        "Authorization": f"Bearer {session_token}",
                    },
                ),
                timeout=30,
            ).read()
        )
        key = key_resp.get("key")
        if not key:
            fail("Key issuance succeeded but no key material was returned.")
        subprocess.run(
            ["hermes", "config", "set", "model.api_key", key, "--force"],
            check=True,
        )
        print("Model key provisioned (shown exactly once) and stored in config.")
    print(
        "Done. Start the agent with: hermes\n"
        "Your device enrolls automatically on first run; an organization "
        "admin approves it and governance policies apply."
    )


if __name__ == "__main__":
    main()
'''

