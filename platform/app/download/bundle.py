def build_bundle(
    *,
    slug: str,
    api_base: str,
    branding: dict[str, Any],
    litellm_base_url: str,
    model: str = DEFAULT_MODEL,
    oidc_issuer_url: str,
    oidc_client_id: str,
) -> tuple[bytes, str, str]:
    """-> (tarball_bytes, sha256_hex, filename). Real, in-memory, no cache.

    `api_base` is the control-plane origin the employee downloaded from
    (D-023-06); `branding` is the tenant's PUBLISHED effective branding.
    """
    settings = get_settings()
    plugin_dir = Path(settings.hermes_plugin_dir)
    if not (plugin_dir / "plugin.yaml").is_file():
        raise FileNotFoundError(
            f"trust-agent-governance plugin tree not found at {plugin_dir} "
            "(settings.hermes_plugin_dir / Dockerfile COPY)"
        )
    version = plugin_version(plugin_dir)
    root = f"trust-agent-{slug}"
    skin = _skin_yaml(slug, branding)

    install_sh = (
        _INSTALL_SH
        .replace("__SLUG__", slug)
        .replace("__API_BASE__", api_base)
        .replace("__LITELLM_BASE__", litellm_base_url)
        .replace("__MODEL__", model)
        .replace("__SKIN_YAML__", skin.rstrip("\n"))
    )
    trust_login = (
        _TRUST_LOGIN
        .replace("__ISSUER__", oidc_issuer_url)
        .replace("__CLIENT_ID__", oidc_client_id)
        .replace("__API_BASE__", api_base)
    )
    readme = (
        _README
        .replace("__SLUG__", slug)
        .replace("{product_name}", branding.get("product_name") or "Trust Agent")
        .replace("{org}", slug)
        .replace("{slug}", slug)
    )

    members: dict[str, bytes] = {
        f"{root}/install.sh": install_sh.encode(),
        f"{root}/trust-login": trust_login.encode(),
        f"{root}/README.md": readme.encode(),
        # Skin como miembro de primera clase (spec 034, D-034-02): el
        # instalador CLI lo copia del tarball — fuente única del branding.
        # El install.sh del desktop sigue horneándolo inline (retrocompatible).
        f"{root}/skin.yaml": skin.encode(),
    }

    # Plugin tree — verbatim copy minus build artifacts.
    for path in sorted(plugin_dir.rglob("*")):
        if path.is_dir():
            continue
        if any(part in _EXCLUDE_DIRS for part in path.parts):
            continue
        if path.suffix in _EXCLUDE_SUFFIXES:
            continue
        rel = path.relative_to(plugin_dir)
        members[f"{root}/plugin/trust-agent-governance/{rel.as_posix()}"] = (
            path.read_bytes()
        )

    manifest = {
        "slug": slug,
        "org_code": slug,
        "api_base": api_base,
        "litellm_base_url": litellm_base_url,
        "model": model,
        "oidc_issuer_url": oidc_issuer_url,
        "oidc_client_id": oidc_client_id,
        "branding": {
            "product_name": branding.get("product_name"),
            "tagline": branding.get("tagline"),
            "accent_color": branding.get("accent_color"),
            "version": branding.get("version"),
        },
        "plugin": "trust-agent-governance",
        "plugin_version": version,
        "spec": "023-hermes-download",
        "members_sha256": {
            name: hashlib.sha256(data).hexdigest()
            for name, data in sorted(members.items())
        },
    }
    members[f"{root}/manifest.json"] = json.dumps(
        manifest, indent=2, sort_keys=True
    ).encode()

    buf = io.BytesIO()
    with tarfile.open(
        mode="w:gz", fileobj=buf, format=tarfile.PAX_FORMAT
    ) as tar:
        for name, data in sorted(members.items()):
            info = tarfile.TarInfo(name=name)
            info.size = len(data)
            info.mtime = 0  # determinista: el sha del tarball solo depende del contenido
            executable = name.endswith(("install.sh", "trust-login"))
            info.mode = 0o755 if executable else 0o644
            tar.addfile(info, io.BytesIO(data))
    payload = buf.getvalue()
    return payload, hashlib.sha256(payload).hexdigest(), (
        f"trust-agent-{slug}-{version}.tar.gz"
    )
